-- ============================================================================
-- 0018 — RITUAIS DE GESTÃO neste portal (16/11/2026)
--
-- Pedido dela: "CTESK e Xipp add Rituais de Gestão (canônico)". É o módulo
-- canônico do Portal Flórida, o mesmo do RQ, WR, Inexx e 3Clicks: o Checkpoint
-- deste cliente e as pendências/decisões combinadas nele, GRAVADOS AQUI depois
-- que a Flórida "levar os Rituais" (Fechamento › Portais dos clientes); a
-- Flórida guarda a cópia (a cada 15 min) e o que é só dela (Outlook,
-- participantes, horas do Timesheet). Até lá a tela lê e grava lá, pela ponte.
--
-- Este SQL:
--   1. abre a faixa "Gestão" no Menu Principal e cria o card `rituais` no
--      catálogo (core.modulos, 0014) — é ele que deixa `conceder_modulo` dar
--      o acesso (a função recusa módulo que não está no catálogo);
--   2. deixa os Perfis de acesso (0012) incluírem o módulo `rituais`;
--   3. a régua do módulo:
--        lê    = quem tem o módulo `rituais`, ou o admin do PORTAL (0013);
--        grava = pode_gravar_modulo('rituais') — editor/admin do módulo, ou o
--                admin do portal. Papel "leitura" só lê;
--   4. as tabelas do pacote canônico liliane-hiramoto/fechamento-core
--      (src/vendor/fechamento-core/sql/rituais.sql), coladas aqui inteiras.
--
-- O código pode ir ANTES: sem as tabelas, a tela segue a ponte com a Flórida.
-- Idempotente. Supabase › SQL Editor › New query › colar tudo › Run.
-- ============================================================================

begin;

-- ---------- 1. o card ----------
alter table core.modulos drop constraint if exists modulos_grupo_check;
alter table core.modulos add constraint modulos_grupo_check check (grupo in ('Fiscal', 'Gestão', 'Configurações'));

insert into core.modulos (key, label, descricao, emoji, href, grupo, status, sem_gate, so_admin, ordem) values
  ('rituais', 'Rituais de Gestão', 'As pendências combinadas com a Flórida nos Checkpoints: quem responde, o prazo e com quem está a bola.', '📌', '/rituais', 'Gestão', 'ativo', false, false, 10)
on conflict (key) do nothing;

-- ---------- 2. os perfis de acesso ----------
alter table public.perfil_acesso_itens drop constraint if exists perfil_acesso_itens_modulo_check;
alter table public.perfil_acesso_itens add constraint perfil_acesso_itens_modulo_check
  check (modulo in ('tributos', 'cnpj', 'y570', 'cpf', 'rituais'));

-- ---------- 3. a régua ----------
create or replace function public.rituais_le()
returns boolean language sql stable security definer set search_path = public as $$
  select public.tem_modulo('rituais') or public.eh_admin_portal();
$$;
create or replace function public.rituais_grava()
returns boolean language sql stable security definer set search_path = public as $$
  select public.pode_gravar_modulo('rituais');
$$;
revoke all on function public.rituais_le() from public;
revoke all on function public.rituais_grava() from public;
grant execute on function public.rituais_le() to authenticated;
grant execute on function public.rituais_grava() to authenticated;

-- ---------- 4. as tabelas (fechamento-core, sql/rituais.sql) ----------
create table if not exists public.rituais_reunioes (
  id                  bigint generated by default as identity primary key,
  -- um Checkpoint por cliente por data (0237 da Flórida): aqui o cliente é o portal
  data                date not null unique,
  empresa_cnpjs       text[] not null default '{}' check (cardinality(empresa_cnpjs) = 0 or array_to_string(empresa_cnpjs, ',') ~ '^\d{14}(,\d{14})*$'),
  status              text not null default 'ABERTA' check (status in ('ABERTA','ENCERRADA')),
  situacao            text not null default 'PREVISTA' check (situacao in ('PREVISTA','REALIZADA','CANCELADA')),
  motivo_cancelamento text,
  local               text,
  hora_inicio         time,
  hora_fim            time check (hora_fim is null or hora_inicio is null or hora_fim > hora_inicio),
  observacoes         text,
  encerrada_em        timestamptz,
  criado_em           timestamptz not null default now(),
  atualizado_em       timestamptz not null default now(),
  -- a regra da 0178 da Flórida: cancelada exige o motivo
  constraint rituais_reunioes_motivo_chk check (situacao <> 'CANCELADA' or length(trim(coalesce(motivo_cancelamento, ''))) > 0)
);

create table if not exists public.rituais_pautas (
  id            bigint generated by default as identity primary key,
  reuniao_id    bigint not null references public.rituais_reunioes(id) on delete cascade,
  titulo        text not null check (length(trim(titulo)) > 0),
  area          text not null default '',
  minutos       int  not null default 5 check (minutos >= 0),
  ordem         int  not null default 0,
  fonte         text not null default 'livre',
  pontos        text,
  pontos_por    text,
  criado_em     timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);
create index if not exists rituais_pautas_reuniao on public.rituais_pautas (reuniao_id, ordem);

create table if not exists public.rituais_acoes (
  id              bigint generated by default as identity primary key,
  reuniao_id      bigint references public.rituais_reunioes(id) on delete set null,
  natureza        text not null default 'ACAO' check (natureza in ('ACAO','DECISAO')),
  tema            text,
  acao            text not null check (length(trim(acao)) between 1 and 4000),
  contexto        text,
  prazo           date,
  prazo_texto     text,
  status          text not null default 'ABERTA' check (status in ('ABERTA','CONCLUIDA','CANCELADA')),
  andamento       text not null default 'EM_ANDAMENTO' check (andamento in ('NAO_INICIADA','EM_ANDAMENTO','AGUARDANDO')),
  bola_com        text check (bola_com is null or bola_com in ('FLORIDA','CLIENTE')),
  identificada_em date,
  concluida_em    date,
  cliente_nome    text,
  empresa_cnpjs   text[] not null default '{}' check (cardinality(empresa_cnpjs) = 0 or array_to_string(empresa_cnpjs, ',') ~ '^\d{14}(,\d{14})*$'),
  criado_em       timestamptz not null default now(),
  atualizado_em   timestamptz not null default now()
);
create index if not exists rituais_acoes_reuniao on public.rituais_acoes (reuniao_id);

-- Responsável: e-mail (pessoa da Flórida ou usuário do portal) OU nome livre.
create table if not exists public.rituais_acao_responsaveis (
  id         bigint generated by default as identity primary key,
  acao_id    bigint not null references public.rituais_acoes(id) on delete cascade,
  email      text check (email is null or email = lower(email)),
  nome_livre text check (nome_livre is null or length(trim(nome_livre)) > 0),
  ordem      int not null default 0,
  constraint rituais_acao_responsaveis_um_chk check (num_nonnulls(email, nome_livre) = 1)
);
create index if not exists rituais_acao_responsaveis_acao on public.rituais_acao_responsaveis (acao_id);

-- O histórico só se ACRESCENTA (a regra da 0227 da Flórida).
create table if not exists public.rituais_acao_historico (
  id          bigint generated by default as identity primary key,
  acao_id     bigint not null references public.rituais_acoes(id) on delete cascade,
  tipo        text not null default 'COMENTARIO' check (tipo in ('COMENTARIO','STATUS','COBRANCA')),
  texto       text not null check (length(trim(texto)) between 1 and 4000),
  -- a data do fato (hoje, ou a da anotação trazida da Flórida)
  data        date not null default (now() at time zone 'America/Sao_Paulo')::date,
  autor_email text,
  autor_nome  text,
  origem      text not null default 'portal' check (origem in ('portal','florida')),
  criado_em   timestamptz not null default now()
);
create index if not exists rituais_acao_historico_acao on public.rituais_acao_historico (acao_id, data);
create index if not exists rituais_acao_historico_criado on public.rituais_acao_historico (criado_em);

-- Lápides: o que foi apagado, para a cópia incremental da Flórida tirar também.
create table if not exists public.rituais_apagados (
  tabela     text not null check (tabela in ('reunioes','pautas','acoes')),
  id         bigint not null,
  apagado_em timestamptz not null default now(),
  primary key (tabela, id)
);

-- ── carimbo e lápide (as funções são as do cronograma, recriadas aqui para
--    o arquivo valer sozinho) ──
create or replace function public.rituais_carimbo() returns trigger
language plpgsql set search_path = public as $$
begin new.atualizado_em := now(); return new; end $$;

create or replace function public.rituais_lapide() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.rituais_apagados (tabela, id)
  values (tg_argv[0], old.id)
  on conflict (tabela, id) do update set apagado_em = now();
  return old;
end $$;
revoke all on function public.rituais_lapide() from public;

-- Mudar responsável carimba a ação: a cópia leva os responsáveis junto da ação.
create or replace function public.rituais_carimba_acao() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  update public.rituais_acoes set atualizado_em = now()
   where id = coalesce(new.acao_id, old.acao_id);
  return null;
end $$;
revoke all on function public.rituais_carimba_acao() from public;

drop trigger if exists carimbo on public.rituais_reunioes;
create trigger carimbo before update on public.rituais_reunioes for each row execute function public.rituais_carimbo();
drop trigger if exists carimbo on public.rituais_pautas;
create trigger carimbo before update on public.rituais_pautas for each row execute function public.rituais_carimbo();
drop trigger if exists carimbo on public.rituais_acoes;
create trigger carimbo before update on public.rituais_acoes for each row execute function public.rituais_carimbo();
drop trigger if exists carimba_acao on public.rituais_acao_responsaveis;
create trigger carimba_acao after insert or update or delete on public.rituais_acao_responsaveis
  for each row execute function public.rituais_carimba_acao();

drop trigger if exists lapide on public.rituais_reunioes;
create trigger lapide after delete on public.rituais_reunioes for each row execute function public.rituais_lapide('reunioes');
drop trigger if exists lapide on public.rituais_pautas;
create trigger lapide after delete on public.rituais_pautas for each row execute function public.rituais_lapide('pautas');
drop trigger if exists lapide on public.rituais_acoes;
create trigger lapide after delete on public.rituais_acoes for each row execute function public.rituais_lapide('acoes');

-- ── RLS: a régua do portal ──
alter table public.rituais_reunioes          enable row level security;
alter table public.rituais_pautas            enable row level security;
alter table public.rituais_acoes             enable row level security;
alter table public.rituais_acao_responsaveis enable row level security;
alter table public.rituais_acao_historico    enable row level security;
alter table public.rituais_apagados          enable row level security;  -- sem política: só o servidor

do $$
declare t text;
begin
  foreach t in array array['rituais_reunioes','rituais_pautas','rituais_acoes','rituais_acao_responsaveis'] loop
    execute format('drop policy if exists "rit ler" on public.%I', t);
    execute format('drop policy if exists "rit gravar" on public.%I', t);
    execute format('drop policy if exists "rit alterar" on public.%I', t);
    execute format('drop policy if exists "rit apagar" on public.%I', t);
    execute format('create policy "rit ler" on public.%I for select to authenticated using (public.rituais_le())', t);
    execute format('create policy "rit gravar" on public.%I for insert to authenticated with check (public.rituais_grava())', t);
    execute format('create policy "rit alterar" on public.%I for update to authenticated using (public.rituais_grava()) with check (public.rituais_grava())', t);
    execute format('create policy "rit apagar" on public.%I for delete to authenticated using (public.rituais_grava())', t);
  end loop;
end $$;

-- Histórico: ler e acrescentar, nunca alterar nem apagar.
drop policy if exists "rit ler" on public.rituais_acao_historico;
drop policy if exists "rit gravar" on public.rituais_acao_historico;
create policy "rit ler" on public.rituais_acao_historico for select to authenticated using (public.rituais_le());
create policy "rit gravar" on public.rituais_acao_historico for insert to authenticated with check (public.rituais_grava());

-- Depois de trazer o histórico da Flórida com os MESMOS ids, o contador de
-- cada tabela anda para depois do maior id. Só o servidor (service role) chama.
create or replace function public.rituais_acertar_sequencias() returns void
language plpgsql security definer set search_path = public as $$
begin
  perform setval(pg_get_serial_sequence('public.rituais_reunioes', 'id'), greatest(coalesce((select max(id) from public.rituais_reunioes), 0), 1));
  perform setval(pg_get_serial_sequence('public.rituais_pautas', 'id'), greatest(coalesce((select max(id) from public.rituais_pautas), 0), 1));
  perform setval(pg_get_serial_sequence('public.rituais_acoes', 'id'), greatest(coalesce((select max(id) from public.rituais_acoes), 0), 1));
  perform setval(pg_get_serial_sequence('public.rituais_acao_responsaveis', 'id'), greatest(coalesce((select max(id) from public.rituais_acao_responsaveis), 0), 1));
  perform setval(pg_get_serial_sequence('public.rituais_acao_historico', 'id'), greatest(coalesce((select max(id) from public.rituais_acao_historico), 0), 1));
end $$;
revoke all on function public.rituais_acertar_sequencias() from public;

grant select, insert, update, delete on public.rituais_reunioes, public.rituais_pautas,
  public.rituais_acoes, public.rituais_acao_responsaveis to authenticated;
grant select, insert on public.rituais_acao_historico to authenticated;
-- O histórico só se acrescenta: no Supabase toda tabela nova nasce com UPDATE e
-- DELETE para authenticated (default privileges); aqui eles saem.
revoke update, delete, truncate on public.rituais_acao_historico from authenticated;
revoke all on public.rituais_reunioes, public.rituais_pautas, public.rituais_acoes,
  public.rituais_acao_responsaveis, public.rituais_acao_historico, public.rituais_apagados from anon;
grant execute on function public.rituais_acertar_sequencias() to service_role;

commit;

-- Conferência (roda colada, uma consulta só). Esperado: 6 · 6 · 2 · 1
select (select count(*) from pg_tables where schemaname = 'public' and tablename like 'rituais\_%')
    || ' · ' || (select count(*) from pg_tables where schemaname = 'public' and tablename like 'rituais\_%' and rowsecurity)
    || ' · ' || (select count(*) from pg_proc where proname in ('rituais_le', 'rituais_grava'))
    || ' · ' || (select count(*) from core.modulos where key = 'rituais') as conferencia;
